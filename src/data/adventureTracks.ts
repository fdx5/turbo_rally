import { CatmullRomCurve3, Vector3 } from 'three';
import type { ShortcutDef, TrackDef } from './tracks';
import { roundRoute, type Vec3T } from '../tracks/path';

// Authored in plan-view x/z/height. No rotated/mirrored copies: every outline,
// corner sequence, fork, elevation profile and jump station is designed separately.
type Row = [number, number, number];
type Branch = {
  from: number;
  to: number;
  via: Row[];
  label: string;
  width?: number;
  surface?: ShortcutDef['surface'];
  boost?: boolean;
};
type Design = Pick<TrackDef, 'id' | 'no' | 'name' | 'theme' | 'desc' | 'laps'> & {
  seconds: number;
  metres: number;
  rows: Row[];
  branches: Branch[];
  jump: number;
} & Partial<
    Pick<
      TrackDef,
      'bpm' | 'width' | 'water' | 'bridge' | 'adventures' | 'tunnel' | 'zones' | 'voidWorld' | 'lowGravity'
    >
  >;

function course(d: Design): TrackDef {
  const convert = ([x, z, y]: Row): Vec3T => [x, y, z];
  let pts = roundRoute(d.rows.map(convert), true);
  const curveFor = (p: Vec3T[]) =>
    new CatmullRomCurve3(
      p.map((p) => new Vector3(...p)),
      true,
      'centripetal',
    );
  // Scale only the plan, keeping authored elevations and the road width human-sized.
  let scale = 1;
  for (let pass = 0; pass < 3; pass++) {
    const length = curveFor(pts).getLength();
    const ratio = d.metres / length;
    scale *= ratio;
    pts = pts.map(([x, y, z]) => [x * ratio, y, z * ratio]);
  }
  const curve = curveFor(pts),
    lengthM = curve.getLength();
  const samples = curve.getSpacedPoints(4096);
  const station = (x: number, z: number, y: number) => {
    let best = Infinity,
      index = 0;
    samples.forEach((p, i) => {
      const distance = (p.x - x * scale) ** 2 + (p.z - z * scale) ** 2 + (p.y - y) ** 2 * 4;
      if (distance < best) {
        best = distance;
        index = i;
      }
    });
    return index / 4096;
  };
  const at = (index: number) => station(...d.rows[index]);
  const shortcuts: ShortcutDef[] = d.branches.map((b) => ({
    // Fork on the approach and merge after the corner, not at its apex.
    fromU: at(b.from) - 85 / lengthM,
    toU: at(b.to) + 85 / lengthM,
    via: b.via.map(([x, z, y]) => [x * scale, y, z * scale]),
    width: b.width ?? 18,
    surface: b.surface ?? 'road',
    boostPad: b.boost ?? true,
    label: b.label,
  }));
  const a = d.rows[d.jump],
    b = d.rows[(d.jump + 1) % d.rows.length];
  const lip = station(a[0] * 0.45 + b[0] * 0.55, a[1] * 0.45 + b[1] * 0.55, a[2] * 0.45 + b[2] * 0.55);
  const lapTargetMs = d.seconds * 1000;
  const total = lapTargetMs * d.laps;
  return {
    id: d.id,
    no: d.no,
    name: d.name,
    theme: d.theme,
    desc: d.desc,
    bpm: d.bpm ?? 145,
    points: pts,
    width: d.width ?? 23,
    shoulder: 4,
    laps: d.laps,
    lapTargetMs,
    lengthM,
    boostPads: [0.035, 0.19, 0.39, 0.61, 0.79]
      .map((u) => ({ u, t: 0 }))
      .concat({ u: lip - 30 / lengthM, t: 0 }),
    itemRows: [0.09, 0.24, 0.42, 0.57, 0.73, 0.89],
    coins: [
      { u: 0.13, t: -4, n: 6 },
      { u: 0.33, t: 4, n: 6 },
      { u: 0.68, t: 0, n: 7 },
    ],
    shortcuts,
    hazards: [],
    zones: d.zones ?? [],
    ramps: [{ u: lip, len: 14, h: 4.8, t0: -11.5, t1: 11.5 }],
    gaps: [{ u0: lip + 1 / lengthM, u1: lip + 10 / lengthM }],
    noWall: [{ u0: lip - 6 / lengthM, u1: lip + 15 / lengthM, side: 'both' }],
    medals: { gold: Math.round(total * 0.88), silver: total, bronze: Math.round(total * 1.2) },
    par: Math.round(total * 1.12),
    bridge: d.bridge,
    adventures: d.adventures,
    tunnel: d.tunnel,
    water: d.water,
    voidWorld: d.voidWorld,
    lowGravity: d.lowGravity,
  };
}

