import { chromium } from 'playwright';
const out = process.argv[2];
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-angle=d3d11', '--enable-gpu'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errs = [];
page.on('pageerror', (e) => errs.push(e.message));
await page.goto('http://localhost:5173/');
await page.waitForTimeout(4000);
await page.getByText('회원가입', { exact: true }).first().click();
await page.waitForTimeout(500);
const u = 'player_' + Math.floor(Math.random() * 1e5);
await page.getByPlaceholder('아이디').fill(u);
await page.getByPlaceholder('비밀번호 (8자').fill('turbo1234');
await page.getByPlaceholder('비밀번호 확인').fill('turbo1234');
await page.getByPlaceholder('닉네임').fill('달려라모모');
await page.screenshot({ path: `${out}/s1_signup.png` });
await page.getByText('가입하기').click();
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}/s2_after.png` });
await page.getByText('달려라모모').first().click();
await page.waitForTimeout(1500);
await page.getByText('상점').first().click();
await page.waitForTimeout(2500);
await page.locator('.btn.small', { hasText: '구매' }).first().click();
await page.waitForTimeout(500);
await page.getByText('구매하기').click();
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/s3_bought.png` });
await page.getByText('바로 장착하기').click();
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/s4_equipped.png` });
console.log('user', u, 'errors', errs);
await browser.close();
