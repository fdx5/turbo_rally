// End-to-end UI flow with screenshots: node tools/qa/flow.mjs <outDir>
import { chromium } from 'playwright';
const out = process.argv[2];
const base = process.argv[3] ?? 'http://localhost:5173/';
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-angle=d3d11', '--enable-gpu', '--ignore-gpu-blocklist', '--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const logs = [];
page.on('console', (m) => { const t = m.text(); if (!/vite|X4122|deprecated|DevTools|404/.test(t)) logs.push(`[${m.type()}] ${t.slice(0, 240)}`); });
page.on('pageerror', (e) => logs.push(`[pageerror] ${e.message} ${e.stack?.split('\n')[1] ?? ''}`));
const shot = async (n) => { await page.screenshot({ path: `${out}/${n}.png` }); console.log('shot', n, 'fps', await page.evaluate(() => window.__fps)); };
const click = async (text) => { await page.getByText(text, { exact: false }).first().click(); await page.waitForTimeout(700); };
await page.goto(base);
await page.waitForTimeout(4500);
await shot('01_title');
await click('게스트로 시작');
await page.waitForTimeout(1500);
await shot('02_menu');
await click('대전 레이스');
await shot('03_mode');
await click('보통');
await page.waitForTimeout(800);
await shot('04_track');
await click('캔디 쿠키 타운');
await page.waitForTimeout(2500);
await shot('05_character');
await page.locator('.card').nth(3).click();
await page.waitForTimeout(1500);
await shot('05b_char_pick');
await click('다음');
await page.waitForTimeout(2500);
await shot('06_vehicle');
await click('출발');
await page.waitForTimeout(6000);
await shot('07_race_intro');
await page.keyboard.press('Space');
await page.keyboard.down('ArrowUp');
await page.waitForTimeout(6000);
await shot('08_race');
await page.keyboard.down('ArrowRight');
await page.keyboard.down('Space');
await page.waitForTimeout(1400);
await shot('09_drift');
await page.keyboard.up('Space');
await page.keyboard.up('ArrowRight');
await page.waitForTimeout(3000);
await shot('10_race2');
console.log(logs.slice(0, 30).join('\n'));
await browser.close();
